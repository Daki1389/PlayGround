function buildFullSchedule() {
  const ids = TEAMS.map((team) => team.id)
  const fixed = ids[0]
  const rest = ids.slice(1)
  const n = rest.length
  const firstHalf = []

  for (let round = 0; round < n; round += 1) {
    const pairs = []
    const fixedHome = round % 2 === 0
    pairs.push(fixedHome ? [fixed, rest[round % n]] : [rest[round % n], fixed])
    for (let i = 1; i <= Math.floor(n / 2); i += 1) {
      const a = rest[(round + i) % n]
      const b = rest[(round - i + n) % n]
      pairs.push(i % 2 === 0 ? [b, a] : [a, b])
    }
    firstHalf.push(pairs)
  }

  const secondHalf = firstHalf.map((pairs) => pairs.map(([home, away]) => [away, home]))
  return [...firstHalf, ...secondHalf]
}

const BASE_DATE = Date.UTC(2027, 0, 9, 15, 0, 0) // Sat 9 Jan 2027, 15:00 UTC
const ALL_ROUNDS = buildFullSchedule()

export const INITIAL_FIXTURES = ALL_ROUNDS.flatMap((pairs, index) => {
  const round = index + 1
  if (round < START_MATCHDAY) return []
  return pairs.map(([homeId, awayId], matchIndex) => {
    const isSunday = matchIndex === 8 || matchIndex === 9
    const date = new Date(BASE_DATE + (round - START_MATCHDAY) * 7 * 86_400_000 + (isSunday ? 86_400_000 : 0) + matchIndex * 20 * 60_000)
    return {
      id: `r${round}-${homeId}-${awayId}`,
      round,
      homeId,
      awayId,
      date: date.toISOString(),
      played: false,
      homeGoals: null,
      awayGoals: null,
    }
  })
})

